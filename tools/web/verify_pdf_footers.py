"""Check A4 page geometry, footer isolation, image placement and branding."""
from pathlib import Path
import fitz
root=Path('build/pdf-footer-checks')
for path in sorted(root.glob('*.pdf')):
 doc=fitz.open(path); assert len(doc)>2,path
 all_text=''.join(p.get_text() for p in doc)
 assert ('Generated by Ripot' in all_text)==path.stem.endswith('-free'),path
 assert 'QA SIGNATURE MARKER' in all_text,path
 signature_page=None;image_pages=[]
 for index,page in enumerate(doc):
  assert abs(page.rect.width-595.28)<2 and abs(page.rect.height-841.89)<2,path
  words=page.get_text('words')
  footers=[w for w in words if w[1]>page.rect.height-100 and w[4] in ('Generated','LETTERHEAD','A4')]
  assert footers,(path,index,'missing letterhead footer')
  boundary=min(w[1] for w in footers)-3
  # Text blocks above the reserved footer zone and every raster image must fit.
  for block in page.get_text('dict')['blocks']:
   if block['type']==1:
    assert block['bbox'][3]<=boundary,(path,index,'image overlaps footer')
    image_pages.append(index)
   else:
    for line in block['lines']:
     text=''.join(s['text'] for s in line['spans'])
     if any(x in text for x in ['QA LETTERHEAD FOOTER','A4 PRINT CHECK','Generated by Ripot']):continue
     assert line['bbox'][3]<=boundary,(path,index,text,'text overlaps footer')
     if 'QA SIGNATURE MARKER' in text:signature_page=index
  if index==len(doc)-1:
   page.get_pixmap(matrix=fitz.Matrix(1.4,1.4)).save(str(root/(path.stem+'-last.png')))
 assert signature_page is not None,path
 if path.stem.startswith('images'): assert image_pages and max(image_pages)<=signature_page,path
 if path.stem.startswith('attachments'): assert image_pages and max(image_pages)>signature_page,path
 print(path.name, len(doc),'pages: A4, footer clearance and branding verified')
assert len(list(root.glob('*.pdf')))==6
